const DEFAULT_AVATARS = ['🕵️', '👳‍♂️', '🧕', '👩‍🦰', '👨‍🎨', '👩‍🌾', '👨‍🎓', '👩‍🏫', '👨‍💻', '👳'];
CHARACTERS.forEach((c, idx) => {
  c.avatar = c.avatar || DEFAULT_AVATARS[idx % DEFAULT_AVATARS.length];
  c.greeting = c.greeting || c.dialogues?.greeting || c.intro;
  c.role = c.role || c.title;
  c.specialty = c.specialty || `${c.outfit} • ${c.personality}`;
});

export function getCharacterById(id: string): CharacterProfile {
  const found = CHARACTERS.find((c) => c.id === id);
  return found || CHARACTERS[0];
}

export function getRandomCharacter(): CharacterProfile {
  const idx = Math.floor(Math.random() * CHARACTERS.length);
  return CHARACTERS[idx];
}
